! Same-binary numerical checkpoint for serial or k-only MPI full-support fast-PR HSE.
! This module owns no FFT plans, C pointers, accelerators or communicators.
! Callers authenticate the archive/configuration and initialize the fresh CPU
! kernel by exx_refresh before read (operator construction, no propagation).
module hse_checkpoint
 use iso_fortran_env,only:int64
 use,intrinsic::ieee_arithmetic,only:ieee_is_finite
 use exx_rt_state,only:s_exx_rt_state
 use exx_ace,only:s_exx_ace
 use exx_factor_history,only:s_factor_history
 use exx_k_exchange,only:exx_k_kernel
 implicit none
 private
 public::hse_checkpoint_write,hse_checkpoint_read
 type numeric_payload
  logical::exx_freeze=.false.,exx_force_full_action=.false.
  logical::exx_adaptive_ready=.false.,exx_support_changed=.false.
  real(8)::exx_exchange_energy=0d0
  real(8),allocatable::cached_occupation(:,:)
  complex(8),allocatable::cached_action(:,:,:)
  logical::finite_support_localized=.true.,radius_warning_reported=.false.
  logical::adaptive_active=.false.,cached_adaptive_ready=.false.
  type(s_exx_ace)::scf_damped_ace,ace,initial_ace,midpoint_ace
  logical::scf_operator_damped=.false.
  type(s_factor_history),allocatable::factor_history(:),ptcn_history(:)
  logical::factor_initialized=.false.,factor_configured=.false.,factor_experiment=.false.,factor_learned=.false.
  logical::factor_prediction_installed=.false.,factor_all_ready=.false.
  real(8),allocatable::factor_occupation(:,:,:)
  integer::factor_step=0
  character(512)::factor_restart_directory=''
  integer::factor_restart_step=-1
  integer::ptcn_accepted_step=0
  logical::ptcn_attempted=.false.,ptcn_predicted=.false.
  real(8)::ptcn_history_dt=0d0
  complex(8),allocatable::full_source(:,:,:),initial_source(:,:,:)
  logical::taylor_active=.false.,taylor_midpoint=.false.
  complex(8),allocatable::cached_source(:,:,:),target_work(:,:,:),action_work(:,:,:)
  logical::reported_team=.false.
  integer(int64)::kernel_pair_fft_pairs=0_int64
 end type
 type kernel_metadata
  integer::n(3)=0,mesh(3)=0,ng=0,nk=0,nq=0,block=0,phase_start=0
  integer,allocatable::order(:),point(:,:),shift(:,:),distance_index(:,:,:,:)
  real(8),allocatable::kernel(:,:,:)
  complex(8),allocatable::phase(:,:)
 end type
contains
 subroutine hse_checkpoint_write(unit,state,status)
  integer,intent(in)::unit
  type(s_exx_rt_state),intent(in)::state
  integer,intent(out)::status
  type(numeric_payload)::value
  type(kernel_metadata)::metadata
  character(32)::magic
  integer(int64)::limit
  status=1
  if(.not.supported(state))return
  call capture(state,value,metadata)
  if(.not.valid_payload(value))return
  limit=element_limit(state)
  status=0;magic='SALMONPY_HSE_NUMERIC_V1'
  write(unit,iostat=status)magic
  if(status/=0)return
  call io_metadata(unit,.false.,metadata,limit,status)
  call io_numeric(unit,.false.,value,limit,status)
  if(status/=0)return
  magic='SALMONPY_HSE_COMPLETE_V1'
  write(unit,iostat=status)magic
 end subroutine
 subroutine hse_checkpoint_read(unit,state,status,validate_only)
  integer,intent(in)::unit
  type(s_exx_rt_state),intent(inout)::state
  integer,intent(out)::status
  logical,optional,intent(in)::validate_only
  type(numeric_payload)::candidate
  type(kernel_metadata)::metadata,expected
  character(32)::magic
  integer(int64)::limit
  status=1
  if(.not.supported(state))return
  call capture(state,candidate,expected)
  metadata=expected
  limit=element_limit(state)
  read(unit,iostat=status)magic
  if(status/=0)return
  if(magic/='SALMONPY_HSE_NUMERIC_V1')then
    status=1;return
  endif
  call io_metadata(unit,.true.,metadata,limit,status)
  if(status/=0)return
  if(.not.same_metadata(metadata,expected))then
    status=1;return
  endif
  call io_numeric(unit,.true.,candidate,limit,status)
  if(status/=0)return
  read(unit,iostat=status)magic
  if(status/=0)return
  if(magic/='SALMONPY_HSE_COMPLETE_V1'.or..not.valid_payload(candidate))then
    status=1;return
  endif
  if(present(validate_only))then
    if(validate_only)return
  endif
  ! Numerical-only commit. In particular, never assign the whole HSE state.
  state%exx_freeze=candidate%exx_freeze
  state%exx_force_full_action=candidate%exx_force_full_action
  state%exx_adaptive_ready=candidate%exx_adaptive_ready
  state%exx_support_changed=candidate%exx_support_changed
  state%exx_exchange_energy=candidate%exx_exchange_energy
  if(allocated(candidate%cached_occupation))then
    call move_alloc(candidate%cached_occupation,state%cached_occupation)
  else
    if(allocated(state%cached_occupation))deallocate(state%cached_occupation)
  endif
  if(allocated(candidate%cached_action))then
    call move_alloc(candidate%cached_action,state%cached_action)
  else
    if(allocated(state%cached_action))deallocate(state%cached_action)
  endif
  state%finite_support_localized=candidate%finite_support_localized
  state%radius_warning_reported=candidate%radius_warning_reported
  state%adaptive_active=candidate%adaptive_active
  state%cached_adaptive_ready=candidate%cached_adaptive_ready
  state%scf_damped_ace=candidate%scf_damped_ace
  state%ace=candidate%ace
  state%initial_ace=candidate%initial_ace
  state%midpoint_ace=candidate%midpoint_ace
  state%scf_operator_damped=candidate%scf_operator_damped
  if(allocated(candidate%factor_history))then
    call move_alloc(candidate%factor_history,state%factor_history)
  else
    if(allocated(state%factor_history))deallocate(state%factor_history)
  endif
  if(allocated(candidate%ptcn_history))then
    call move_alloc(candidate%ptcn_history,state%ptcn_history)
  else
    if(allocated(state%ptcn_history))deallocate(state%ptcn_history)
  endif
  state%factor_initialized=candidate%factor_initialized
  state%factor_configured=candidate%factor_configured
  state%factor_experiment=candidate%factor_experiment
  state%factor_learned=candidate%factor_learned
  state%factor_prediction_installed=candidate%factor_prediction_installed
  state%factor_all_ready=candidate%factor_all_ready
  if(allocated(candidate%factor_occupation))then
    call move_alloc(candidate%factor_occupation,state%factor_occupation)
  else
    if(allocated(state%factor_occupation))deallocate(state%factor_occupation)
  endif
  state%factor_step=candidate%factor_step
  state%factor_restart_directory=candidate%factor_restart_directory
  state%factor_restart_step=candidate%factor_restart_step
  state%ptcn_accepted_step=candidate%ptcn_accepted_step
  state%ptcn_attempted=candidate%ptcn_attempted
  state%ptcn_predicted=candidate%ptcn_predicted
  state%ptcn_history_dt=candidate%ptcn_history_dt
  if(allocated(candidate%full_source))then
    call move_alloc(candidate%full_source,state%full_source)
  else
    if(allocated(state%full_source))deallocate(state%full_source)
  endif
  if(allocated(candidate%initial_source))then
    call move_alloc(candidate%initial_source,state%initial_source)
  else
    if(allocated(state%initial_source))deallocate(state%initial_source)
  endif
  state%taylor_active=candidate%taylor_active
  state%taylor_midpoint=candidate%taylor_midpoint
  if(allocated(candidate%cached_source))then
    call move_alloc(candidate%cached_source,state%cached_source)
  else
    if(allocated(state%cached_source))deallocate(state%cached_source)
  endif
  if(allocated(candidate%target_work))then
    call move_alloc(candidate%target_work,state%target_work)
  else
    if(allocated(state%target_work))deallocate(state%target_work)
  endif
  if(allocated(candidate%action_work))then
    call move_alloc(candidate%action_work,state%action_work)
  else
    if(allocated(state%action_work))deallocate(state%action_work)
  endif
  state%reported_team=candidate%reported_team
  state%native_kernel%pair_fft_pairs=candidate%kernel_pair_fft_pairs
  status=0
 end subroutine
 logical function supported(state) result(ok)
  type(s_exx_rt_state),intent(in)::state
  ok=.false.
  if(.not.state%native_resources_enabled.or..not.allocated(state%native_kernel))return
  if(any(state%native_kernel%n<1).or.state%native_kernel%ng<1.or.state%native_kernel%nk<1)return
  if(allocated(state%native_kernel%accelerator))return
  if(state%native_kernel%nq/=state%native_kernel%nk)return
  if(state%native_symmetry%nfull/=0.or.state%native_symmetry%nrep/=0.or.state%native_symmetry%nsym/=0)return
  if(state%ace%metric_distributed.or.state%initial_ace%metric_distributed.or. &
     state%midpoint_ace%metric_distributed.or.state%scf_damped_ace%metric_distributed)return
  ok=.true.
 end function
 integer(int64) function element_limit(state) result(limit)
  type(s_exx_rt_state),intent(in)::state
  integer(int64)::orbitals,grid,kpoints
  orbitals=1_int64
  if(allocated(state%cached_occupation))orbitals=max(orbitals,size(state%cached_occupation,1,kind=int64))
  if(allocated(state%full_source))orbitals=max(orbitals,size(state%full_source,2,kind=int64))
  if(allocated(state%cached_source))orbitals=max(orbitals,size(state%cached_source,2,kind=int64))
  if(allocated(state%ace%factors))orbitals=max(orbitals,size(state%ace%factors,2,kind=int64))
  grid=int(state%native_kernel%ng,int64);kpoints=int(state%native_kernel%nk,int64)
  ! This is a per-array allocation sanity bound, not a bound on peak RSS.
  limit=max(4096_int64,32_int64*grid*kpoints*orbitals)
 end function
 subroutine capture(state,value,metadata)
  type(s_exx_rt_state),intent(in)::state
  type(numeric_payload),intent(out)::value
  type(kernel_metadata),intent(out)::metadata
  integer::axis
  value%exx_freeze=state%exx_freeze
  value%exx_force_full_action=state%exx_force_full_action
  value%exx_adaptive_ready=state%exx_adaptive_ready
  value%exx_support_changed=state%exx_support_changed
  value%exx_exchange_energy=state%exx_exchange_energy
  if(allocated(state%cached_occupation))value%cached_occupation=state%cached_occupation
  if(allocated(state%cached_action))value%cached_action=state%cached_action
  value%finite_support_localized=state%finite_support_localized
  value%radius_warning_reported=state%radius_warning_reported
  value%adaptive_active=state%adaptive_active
  value%cached_adaptive_ready=state%cached_adaptive_ready
  value%scf_damped_ace=state%scf_damped_ace
  value%ace=state%ace
  value%initial_ace=state%initial_ace
  value%midpoint_ace=state%midpoint_ace
  value%scf_operator_damped=state%scf_operator_damped
  if(allocated(state%factor_history))value%factor_history=state%factor_history
  if(allocated(state%ptcn_history))value%ptcn_history=state%ptcn_history
  value%factor_initialized=state%factor_initialized
  value%factor_configured=state%factor_configured
  value%factor_experiment=state%factor_experiment
  value%factor_learned=state%factor_learned
  value%factor_prediction_installed=state%factor_prediction_installed
  value%factor_all_ready=state%factor_all_ready
  if(allocated(state%factor_occupation))value%factor_occupation=state%factor_occupation
  value%factor_step=state%factor_step
  value%factor_restart_directory=state%factor_restart_directory
  value%factor_restart_step=state%factor_restart_step
  value%ptcn_accepted_step=state%ptcn_accepted_step
  value%ptcn_attempted=state%ptcn_attempted
  value%ptcn_predicted=state%ptcn_predicted
  value%ptcn_history_dt=state%ptcn_history_dt
  if(allocated(state%full_source))value%full_source=state%full_source
  if(allocated(state%initial_source))value%initial_source=state%initial_source
  value%taylor_active=state%taylor_active
  value%taylor_midpoint=state%taylor_midpoint
  if(allocated(state%cached_source))value%cached_source=state%cached_source
  if(allocated(state%target_work))value%target_work=state%target_work
  if(allocated(state%action_work))value%action_work=state%action_work
  value%reported_team=state%reported_team
  value%kernel_pair_fft_pairs=state%native_kernel%pair_fft_pairs
  metadata%n=state%native_kernel%n
  metadata%mesh=state%native_kernel%mesh
  metadata%ng=state%native_kernel%ng
  metadata%nk=state%native_kernel%nk
  metadata%nq=state%native_kernel%nq
  metadata%block=state%native_kernel%block
  metadata%phase_start=state%native_kernel%phase_start
  if(allocated(state%native_kernel%order))metadata%order=state%native_kernel%order
  if(allocated(state%native_kernel%point))metadata%point=state%native_kernel%point
  if(allocated(state%native_kernel%shift))metadata%shift=state%native_kernel%shift
  if(allocated(state%native_kernel%distance_index))then
    ! The kernel initializes only each axis's active rectangle. Padding in the
    ! max-dimension allocation is undefined and must never enter an archive.
    allocate(metadata%distance_index(0:maxval(metadata%n)-1,0:maxval(metadata%n)-1, &
      0:maxval(metadata%mesh)-1,3),source=0)
    do axis=1,3
      metadata%distance_index(0:metadata%n(axis)-1,0:metadata%n(axis)-1,0:metadata%mesh(axis)-1,axis)= &
        state%native_kernel%distance_index(0:metadata%n(axis)-1,0:metadata%n(axis)-1, &
          0:metadata%mesh(axis)-1,axis)
    enddo
  endif
  if(allocated(state%native_kernel%kernel))metadata%kernel=state%native_kernel%kernel
  if(allocated(state%native_kernel%phase))metadata%phase=state%native_kernel%phase
 end subroutine
 logical function same_metadata(a,b) result(ok)
  type(kernel_metadata),intent(in)::a,b
  integer::axis
  ok=.false.
  if(any(a%n/=b%n))return
  if(any(a%mesh/=b%mesh))return
  if(a%ng/=b%ng)return
  if(a%nk/=b%nk)return
  if(a%nq/=b%nq)return
  if(a%block/=b%block)return
  if(a%phase_start/=b%phase_start)return
  if(allocated(a%order).neqv.allocated(b%order))return
  if(allocated(a%order))then
    if(any(shape(a%order)/=shape(b%order)))return
    if(any(lbound(a%order)/=lbound(b%order)))return
    if(any(a%order/=b%order))return
  endif
  if(allocated(a%point).neqv.allocated(b%point))return
  if(allocated(a%point))then
    if(any(shape(a%point)/=shape(b%point)))return
    if(any(lbound(a%point)/=lbound(b%point)))return
    if(any(a%point/=b%point))return
  endif
  if(allocated(a%shift).neqv.allocated(b%shift))return
  if(allocated(a%shift))then
    if(any(shape(a%shift)/=shape(b%shift)))return
    if(any(lbound(a%shift)/=lbound(b%shift)))return
    if(any(a%shift/=b%shift))return
  endif
  if(allocated(a%distance_index).neqv.allocated(b%distance_index))return
  if(allocated(a%distance_index))then
    if(any(shape(a%distance_index)/=shape(b%distance_index)))return
    if(any(lbound(a%distance_index)/=lbound(b%distance_index)))return
    ! Older same-binary archives can contain arbitrary unused padding too.
    do axis=1,3
      if(any(a%distance_index(0:a%n(axis)-1,0:a%n(axis)-1,0:a%mesh(axis)-1,axis)/= &
             b%distance_index(0:b%n(axis)-1,0:b%n(axis)-1,0:b%mesh(axis)-1,axis)))return
    enddo
  endif
  if(allocated(a%kernel).neqv.allocated(b%kernel))return
  if(allocated(a%kernel))then
    if(any(shape(a%kernel)/=shape(b%kernel)))return
    if(any(lbound(a%kernel)/=lbound(b%kernel)))return
    if(any(a%kernel/=b%kernel))return
  endif
  if(allocated(a%phase).neqv.allocated(b%phase))return
  if(allocated(a%phase))then
    if(any(shape(a%phase)/=shape(b%phase)))return
    if(any(lbound(a%phase)/=lbound(b%phase)))return
    if(any(a%phase/=b%phase))return
  endif
  ok=.true.
 end function
 logical function valid_payload(value) result(ok)
  type(numeric_payload),intent(in)::value
  integer::i
  ok=.false.
  if(value%ace%metric_distributed.or.value%initial_ace%metric_distributed.or. &
    value%midpoint_ace%metric_distributed.or.value%scf_damped_ace%metric_distributed)return
  if(.not.ieee_is_finite(value%exx_exchange_energy).or..not.ieee_is_finite(value%ptcn_history_dt))return
  if(value%factor_step<0.or.value%ptcn_accepted_step<0.or.value%ptcn_history_dt<0d0)return
  if(allocated(value%factor_history))then
    do i=lbound(value%factor_history,1),ubound(value%factor_history,1)
      if(.not.valid_history(value%factor_history(i)))return
    enddo
  endif
  if(allocated(value%ptcn_history))then
    do i=lbound(value%ptcn_history,1),ubound(value%ptcn_history,1)
      if(.not.valid_history(value%ptcn_history(i)))return
    enddo
  endif
  ok=.true.
 end function
 logical function valid_history(value) result(ok)
  type(s_factor_history),intent(in)::value
  ok=value%interval>=1.and.value%n_teach>=0.and.value%count>=0.and.value%teachers>=0
  ok=ok.and.all(ieee_is_finite(value%g)).and.all(ieee_is_finite(value%b)).and.all(ieee_is_finite(value%coeff))
 end function
 subroutine io_numeric(unit,reading,value,limit,status)
  integer,intent(in)::unit
  logical,intent(in)::reading
  type(numeric_payload),intent(inout)::value
  integer(int64),intent(in)::limit
  integer,intent(inout)::status
  integer::lo(4),hi(4),i1,k,allocation_status
  integer(int64)::elements,extent
  logical::present_array
  if(status/=0)return
  if(reading)then
    read(unit,iostat=status)value%exx_freeze
  else
    write(unit,iostat=status)value%exx_freeze
  endif
  if(status/=0)return
  if(reading)then
    read(unit,iostat=status)value%exx_force_full_action
  else
    write(unit,iostat=status)value%exx_force_full_action
  endif
  if(status/=0)return
  if(reading)then
    read(unit,iostat=status)value%exx_adaptive_ready
  else
    write(unit,iostat=status)value%exx_adaptive_ready
  endif
  if(status/=0)return
  if(reading)then
    read(unit,iostat=status)value%exx_support_changed
  else
    write(unit,iostat=status)value%exx_support_changed
  endif
  if(status/=0)return
  if(reading)then
    read(unit,iostat=status)value%exx_exchange_energy
  else
    write(unit,iostat=status)value%exx_exchange_energy
  endif
  if(status/=0)return
  present_array=allocated(value%cached_occupation)
  if(reading)then
    read(unit,iostat=status)present_array
  else
    write(unit,iostat=status)present_array
  endif
  if(status/=0)return
  if(reading)then
    if(allocated(value%cached_occupation))deallocate(value%cached_occupation)
  endif
  if(present_array)then
    if(reading)then
      read(unit,iostat=status)lo(1:2),hi(1:2)
      if(status/=0)return
      elements=1_int64
      do k=1,2
        extent=int(hi(k),int64)-int(lo(k),int64)+1_int64
        if(extent<0_int64.or.extent>limit)then
          status=1;return
        endif
        if(extent>0_int64)then
          if(elements>limit/extent)then
            status=1;return
          endif
        endif
        elements=elements*extent
      enddo
      allocate(value%cached_occupation(lo(1):hi(1),lo(2):hi(2)),stat=allocation_status)
      if(allocation_status/=0)then
        status=1;return
      endif
    else
      lo(1:2)=lbound(value%cached_occupation);hi(1:2)=ubound(value%cached_occupation)
      write(unit,iostat=status)lo(1:2),hi(1:2)
      if(status/=0)return
    endif
    if(reading)then
      read(unit,iostat=status)value%cached_occupation
    else
      write(unit,iostat=status)value%cached_occupation
    endif
    if(status/=0)return
  endif
  present_array=allocated(value%cached_action)
  if(reading)then
    read(unit,iostat=status)present_array
  else
    write(unit,iostat=status)present_array
  endif
  if(status/=0)return
  if(reading)then
    if(allocated(value%cached_action))deallocate(value%cached_action)
  endif
  if(present_array)then
    if(reading)then
      read(unit,iostat=status)lo(1:3),hi(1:3)
      if(status/=0)return
      elements=1_int64
      do k=1,3
        extent=int(hi(k),int64)-int(lo(k),int64)+1_int64
        if(extent<0_int64.or.extent>limit)then
          status=1;return
        endif
        if(extent>0_int64)then
          if(elements>limit/extent)then
            status=1;return
          endif
        endif
        elements=elements*extent
      enddo
      allocate(value%cached_action(lo(1):hi(1),lo(2):hi(2),lo(3):hi(3)),stat=allocation_status)
      if(allocation_status/=0)then
        status=1;return
      endif
    else
      lo(1:3)=lbound(value%cached_action);hi(1:3)=ubound(value%cached_action)
      write(unit,iostat=status)lo(1:3),hi(1:3)
      if(status/=0)return
    endif
    if(reading)then
      read(unit,iostat=status)value%cached_action
    else
      write(unit,iostat=status)value%cached_action
    endif
    if(status/=0)return
  endif
  if(reading)then
    read(unit,iostat=status)value%finite_support_localized
  else
    write(unit,iostat=status)value%finite_support_localized
  endif
  if(status/=0)return
  if(reading)then
    read(unit,iostat=status)value%radius_warning_reported
  else
    write(unit,iostat=status)value%radius_warning_reported
  endif
  if(status/=0)return
  if(reading)then
    read(unit,iostat=status)value%adaptive_active
  else
    write(unit,iostat=status)value%adaptive_active
  endif
  if(status/=0)return
  if(reading)then
    read(unit,iostat=status)value%cached_adaptive_ready
  else
    write(unit,iostat=status)value%cached_adaptive_ready
  endif
  if(status/=0)return
  call io_ace(unit,reading,value%scf_damped_ace,limit,status)
  if(status/=0)return
  call io_ace(unit,reading,value%ace,limit,status)
  if(status/=0)return
  call io_ace(unit,reading,value%initial_ace,limit,status)
  if(status/=0)return
  call io_ace(unit,reading,value%midpoint_ace,limit,status)
  if(status/=0)return
  if(reading)then
    read(unit,iostat=status)value%scf_operator_damped
  else
    write(unit,iostat=status)value%scf_operator_damped
  endif
  if(status/=0)return
